// Kairotic · Study 28 · build of the WebAssembly
// stftPitchShift (C++, MIT) → shift.wasm with wasi-sdk (a clang for WebAssembly, no Emscripten), then
// wrapped with glue.mjs into ../kairotic/shift.mjs: one ES module with the WebAssembly inside.
//
//   node studies/28-shift/native/build.mjs
//
// What it needs it fetches once into native/.cache (not in the repository): stftPitchShift at a pinned
// tag, and wasi-sdk for this machine (Linux or macOS, x86_64 or arm64). WASI_SDK=/path uses one you have.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { arch, platform } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const cache = join(here, ".cache");
const LIB_TAG = "v2.0";          // stftPitchShift
const SDK = "25";                // wasi-sdk
mkdirSync(cache, { recursive: true });

const run = (cmd, args, opts) => execFileSync(cmd, args, { stdio: "inherit", ...opts });

// 1. stftPitchShift, at its tag
const lib = join(cache, "stftPitchShift-" + LIB_TAG);
if (!existsSync(lib))
  run("git", ["clone", "--quiet", "--depth", "1", "--branch", LIB_TAG, "https://github.com/jurihock/stftPitchShift", lib]);

// 2. wasi-sdk
let sdk = process.env.WASI_SDK;
if (!sdk) {
  const os = platform() === "darwin" ? "macos" : "linux";
  const cpu = arch() === "arm64" ? "arm64" : "x86_64";
  const name = `wasi-sdk-${SDK}.0-${cpu}-${os}`;
  sdk = join(cache, name);
  if (!existsSync(sdk)) {
    const tgz = join(cache, name + ".tar.gz");
    run("curl", ["-sSL", "-o", tgz, `https://github.com/WebAssembly/wasi-sdk/releases/download/wasi-sdk-${SDK}/${name}.tar.gz`]);
    run("tar", ["xzf", tgz, "-C", cache]);
  }
}

// 3. compile: a reactor (no main), no exceptions (shift.cpp checks what the library would throw on),
//    iostream left out (shim/StftPitchShift/Timer.h comes before the library's own)
const wasm = join(cache, "shift.wasm");
run(join(sdk, "bin", "clang++"), [
  "--target=wasm32-wasip1", "-mexec-model=reactor", "-O3", "-std=c++20", "-fno-exceptions",
  "-I", join(here, "shim"), "-I", join(lib, "cpp"),
  "-Wl,--strip-all", "-Wl,--gc-sections", "-Wl,-z,stack-size=1048576",
  "-o", wasm, join(here, "shift.cpp"),
]);

// 4. the module: glue.mjs with the WebAssembly inside
const b64 = readFileSync(wasm).toString("base64");
// the studies that use it: 28 (offline) and 29 (real time, in an AudioWorklet)
const text = "// Generated by studies/28-shift/native/build.mjs from glue.mjs and shift.cpp — do not edit by hand.\n" +
  readFileSync(join(here, "glue.mjs"), "utf8").replace("%WASM%", b64);
for (const study of ["28-shift", "29-live"]) {
  const dir = join(here, "..", "..", study, "kairotic");
  if (!existsSync(dir)) continue;
  writeFileSync(join(dir, "shift.mjs"), text);
  console.log(`shift.wasm ${readFileSync(wasm).length} bytes → studies/${study}/kairotic/shift.mjs (stftPitchShift ${LIB_TAG}, wasi-sdk ${SDK})`);
}
