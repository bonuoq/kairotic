// Builds the catalog of examples Claude reads when it writes components in Kairotic (Study 16):
// examples/catalog.mjs = { examples: [{ name, category, kind, about, source }] }.
// Claude sees the list (name, category, one line) and reads whole examples with a tool when it needs
// them, so the catalog can grow without the prompt growing.
//
// To add an example: put it in examples/claude/<category>/<name>.(cljs|dsp) with a first line
//   ;; about: …        (ClojureScript)   or   // about: …   (Faust)
// or list an existing file below (`refs`), then run `node examples/build.mjs`.
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname, basename, extname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

// existing components used as examples, where they live
const refs = [
  { name: "knob", category: "controls", file: "components/src/knob.cljs",
    about: "a rotary control with its own view, declared arguments, a gesture and :persist" },
  { name: "adsr~", category: "synth", file: "packages/synth/src/adsr.cljs",
    about: "an envelope with an AudioWorklet carried inside, a drawn view and gestures that rewrite the box" },
  { name: "synth~", category: "synth", file: "packages/synth/src/synth.cljs",
    about: "a polyphonic synthesizer built from Web Audio nodes, one voice per id" },
  { name: "pan~", category: "spatial", file: "packages/spatial/src/pan.cljs",
    about: "the simplest audio component: one Web Audio node, a parameter set by messages, :update" },
  { name: "space~", category: "spatial", file: "packages/spatial/src/space.cljs",
    about: "binaural placement with a 2D pad view, crossfading two HRTF panners" },
  { name: "fifth", category: "cac", file: "components/src/fifth.cljs",
    about: "adds a just fifth above every frequency, keeping voice ids (reader → fifth → synth~)" },
  { name: "drift", category: "cac", file: "components/src/drift.cljs",
    about: "a slow random walk in pitch, different for every voice, with state" },
];

const kindOf = (file, source) =>
  extname(file) === ".dsp" ? "faust" : /:patch\s/.test(source) ? "abstraction" : /:package\s/.test(source) ? "package" : "component";

const aboutOf = (source) => {
  const m = source.match(/^\s*(?:;;|\/\/)\s*about:\s*(.+)$/m);
  return m ? m[1].trim() : "";
};
const withoutAbout = (source) => source.replace(/^\s*(?:;;|\/\/)\s*about:.*\n/m, "");

const examples = [];
for (const r of refs) {
  const source = readFileSync(join(root, r.file), "utf8");
  examples.push({ name: r.name, category: r.category, kind: kindOf(r.file, source), about: r.about, source });
}
const dir = join(here, "claude");
for (const category of readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
  for (const f of readdirSync(join(dir, category)).filter((f) => /\.(cljs|dsp)$/.test(f)).sort()) {
    const source = readFileSync(join(dir, category, f), "utf8");
    const about = aboutOf(source);
    if (!about) throw new Error(category + "/" + f + ": its first line must be an `about:` comment");
    examples.push({ name: basename(f, extname(f)), category, kind: kindOf(f, source), about, source: withoutAbout(source) });
  }
}
writeFileSync(join(here, "catalog.mjs"),
  "// Generated by examples/build.mjs — the examples Claude reads in Kairotic\nexport default " +
  JSON.stringify({ examples }, null, 2) + ";\n");
console.log(examples.map((e) => e.category + "/" + e.name + " (" + e.kind + ")").join("\n"));
