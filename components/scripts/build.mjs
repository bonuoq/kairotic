// Builds one JavaScript module per component from src/<name>.cljs.
// Inside claude.ai a page can only load JS modules from npm (through jsDelivr), so every
// component is published as:  export default { class, version, author, license, doc, source }
// plus dist/index.mjs listing all of them.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const author = typeof pkg.author === "string" ? pkg.author : (pkg.author && pkg.author.name) || "";
mkdirSync(join(root, "dist"), { recursive: true });

const field = (source, key) => {
  const m = source.match(new RegExp(":" + key + "\\s+\"((?:[^\"\\\\]|\\\\.)*)\""));
  return m ? m[1].replace(/\\"/g, '"') : null;
};

const index = [];
for (const file of readdirSync(join(root, "src")).filter((f) => f.endsWith(".cljs")).sort()) {
  const source = readFileSync(join(root, "src", file), "utf8");
  const cls = field(source, "class");
  if (!cls) throw new Error(file + ": missing :class \"…\"");
  const name = file.replace(/\.cljs$/, "");
  const license = field(source, "license") || pkg.license || "";
  const comp = { class: cls, version: pkg.version, author, license, doc: field(source, "doc") || "", source };
  writeFileSync(join(root, "dist", name + ".mjs"),
    "// Generated by scripts/build.mjs from src/" + file + "\nexport default " + JSON.stringify(comp, null, 2) + ";\n");
  index.push({ class: cls, license, doc: comp.doc, file: name + ".mjs" });
  console.log("✓ " + cls + " → dist/" + name + ".mjs");
}
writeFileSync(join(root, "dist", "index.mjs"),
  "// Generated by scripts/build.mjs\nexport default " + JSON.stringify({ package: pkg.name, version: pkg.version, components: index }, null, 2) + ";\n");
