// Builds the official Kairotic packages: for every packages/<name>/src/*.cljs, one module per
// component (dist/<file>.mjs: { class, version, author, license, doc, source }) and the whole package
// in one module (dist/index.mjs: { package, version, api, license, components: [...] }), which is what
// a work imports. Inside claude.ai a page can only load JS modules from npm (through jsDelivr).
//   node packages/build.mjs            every package
//   node packages/build.mjs synth      one
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const field = (source, key) => {
  const m = source.match(new RegExp(":" + key + "\\s+\"((?:[^\"\\\\]|\\\\.)*)\""));
  return m ? m[1].replace(/\\"/g, '"') : null;
};

const only = process.argv[2];
for (const name of readdirSync(here, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
  if (only && name !== only) continue;
  const root = join(here, name);
  if (!existsSync(join(root, "package.json"))) continue;
  const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  const author = typeof pkg.author === "string" ? pkg.author : (pkg.author && pkg.author.name) || "";
  const api = (pkg.kairotic && pkg.kairotic.api) || 1;
  mkdirSync(join(root, "dist"), { recursive: true });
  const components = [];
  for (const file of readdirSync(join(root, "src")).filter((f) => f.endsWith(".cljs")).sort()) {
    const source = readFileSync(join(root, "src", file), "utf8");
    const cls = field(source, "class");
    if (!cls) throw new Error(name + "/" + file + ": missing :class \"…\"");
    const comp = { class: cls, version: pkg.version, author, license: field(source, "license") || pkg.license || "",
                   doc: field(source, "doc") || "", source };
    writeFileSync(join(root, "dist", file.replace(/\.cljs$/, ".mjs")),
      "// Generated by packages/build.mjs from src/" + file + "\nexport default " + JSON.stringify(comp, null, 2) + ";\n");
    components.push(comp);
  }
  const index = { package: pkg.name, version: pkg.version, api, author, license: pkg.license || "",
                  components: components.map(({ class: c, license, doc, source }) => ({ class: c, license, doc, source })) };
  writeFileSync(join(root, "dist", "index.mjs"),
    "// Generated by packages/build.mjs\nexport default " + JSON.stringify(index, null, 2) + ";\n");
  console.log("✓ " + pkg.name + " " + pkg.version + ": " + components.map((c) => c.class).join(", "));
}
